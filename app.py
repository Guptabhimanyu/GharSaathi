import streamlit as st

import json
import os
from pathlib import Path

import llm
import refresh
import loan_calc
import voice
from rag import Retriever, chat_reply, loan_options, personalized_plan
from user_profile import Profile

MANIFEST = Path("data/manifest.json")

try:  # Streamlit Cloud "Secrets" -> environment variables read by llm.py / voice.py
    for _k, _v in st.secrets.items():
        if isinstance(_v, str):
            os.environ.setdefault(_k, _v)
except Exception:
    pass

st.set_page_config(page_title="GharSaathi", page_icon="🏠")


@st.cache_resource(ttl=24 * 3600, show_spinner="Checking for updated scheme documents...")
def get_retriever():
    try:
        refresh.refresh()  # re-checks official sources at most once a day; falls back to cached copies
    except Exception as e:  # network down, site blocked, etc.
        print("refresh failed, using existing index:", e)
    return Retriever()


def _submit_heard():
    st.session_state.queued = st.session_state.heard_edit
    st.session_state.heard_edit = ""


def last_checked() -> str:
    m = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    dates = [v.get("checked_at", "")[:10] for v in m.values() if v.get("checked_at")]
    return max(dates) if dates else "never"


st.title("🏠 GharSaathi")
st.caption("Unofficial guide. Answers come only from official scheme documents. Not official or financial advice; confirm with your urban local body.")

if "profile" not in st.session_state:
    with st.form("intake"):
        st.subheader("A few quick questions")
        occupation = st.selectbox("What work do you do?", [
            "Factory / industrial worker", "Construction worker", "Domestic / gig / informal worker",
            "Student", "Salaried employee (private)", "Self-employed / small business", "Other"])
        income = st.number_input("Monthly household income (₹)", min_value=0, value=15000, step=1000)
        c1, c2 = st.columns(2)
        city = c1.text_input("City", "Gandhinagar")
        state = c2.text_input("State", "Gujarat")
        gender = st.selectbox("Gender", ["Female", "Male", "Other"])
        migrant = st.checkbox("I moved here from another city/state for work or study")
        owns = st.checkbox("My family owns a pucca house anywhere in India")
        employer = st.checkbox("My employer already provides housing")
        proof = st.selectbox("How can you show your income?", ["Salary slips", "Bank statements only", "Mostly cash, no proof"])
        existing_emi = st.number_input("Monthly EMIs you already pay on other loans (₹)", min_value=0, value=0, step=500)
        need = st.selectbox("What do you need?", ["Short-term rental", "Long-term rental", "Own a house", "Not sure"])
        if st.form_submit_button("Show me my options"):
            st.session_state.profile = Profile(occupation, int(income), city, state, gender, migrant, owns, need, employer, proof, int(existing_emi))
            st.rerun()
else:
    profile = st.session_state.profile
    try:
        retriever = get_retriever()
    except FileNotFoundError:
        st.error("The document index is missing. Run `python refresh.py` and commit the `data/` folder, then redeploy.")
        st.stop()
    if "plan" not in st.session_state:
        with st.spinner("Reading the scheme documents..."):
            st.session_state.plan, st.session_state.plan_src = personalized_plan(retriever, profile)
            st.session_state.plan_llm = llm.LAST_PROVIDER
            st.session_state.history = []
    st.markdown(st.session_state.plan)
    st.caption(f"Generated by {st.session_state.get('plan_llm', '')}")
    with st.expander("Sources used"):
        for i, c in enumerate(st.session_state.plan_src, 1):
            link = f" ([source]({c['url']}))" if c.get("url") else ""
            st.markdown(f"**[{i}]** {c.get('label', c['source'])}, p.{c['page']}, checked {c.get('checked') or 'n/a'}{link}")
    if profile.wants_loan():
        st.divider()
        st.subheader("💳 Loan options to explore")
        if "loans" not in st.session_state:
            with st.spinner("Checking loan routes in the scheme documents..."):
                st.session_state.loans, st.session_state.loans_src = loan_options(retriever, profile)
                st.session_state.loans_llm = llm.LAST_PROVIDER
        st.markdown(st.session_state.loans)
        st.caption(f"Generated by {st.session_state.get('loans_llm', '')}. General information, not financial advice.")
        with st.expander("Sources used for loan options"):
            for i, c in enumerate(st.session_state.loans_src, 1):
                link = f" ([source]({c['url']}))" if c.get("url") else ""
                st.markdown(f"**[{i}]** {c.get('label', c['source'])}, p.{c['page']}, checked {c.get('checked') or 'n/a'}{link}")
        with st.expander("Estimate your monthly EMI"):
            c1, c2, c3 = st.columns(3)
            amount = c1.number_input("Loan amount (₹)", min_value=0, value=800000, step=50000)
            rate = c2.number_input("Interest rate % (example value; use the lender's quote)", 0.0, 30.0, 9.0, 0.1)
            years = c3.number_input("Tenure (years)", 1, 30, 15)
            subsidy = st.number_input("Upfront subsidy to deduct (₹), only what the portal/lender confirms", min_value=0, value=0, step=10000)
            e0 = loan_calc.emi(amount, rate, years)
            e1 = loan_calc.emi(max(amount - subsidy, 0), rate, years)
            m1, m2 = st.columns(2)
            m1.metric("EMI without subsidy", f"₹{e0:,.0f}")
            m2.metric("EMI with subsidy", f"₹{e1:,.0f}", delta=f"-₹{e0 - e1:,.0f}" if subsidy else None, delta_color="inverse")
            share = loan_calc.burden(e1, profile.existing_emi, profile.monthly_income)
            st.write(f"Total EMIs would be about **{share:.0%}** of your monthly income.")
            if share > 0.4:
                st.warning("That is a heavy share. Lenders often look for total EMIs well under about half of income (rule of thumb, "
                           "not any one lender's rule), and a high share is risky for you too.")
    st.divider()
    st.subheader("Ask a follow-up")
    for m in st.session_state.history:
        st.chat_message(m["role"]).markdown(m["content"])
    lang_choice = st.radio("Speaking language / बोलने की भाषा", ["Auto", "English", "हिन्दी"], horizontal=True)
    hint = {"English": "en", "हिन्दी": "hi"}.get(lang_choice)
    speak_on = st.toggle("Read answers aloud / उत्तर सुनें", value=False)
    audio = st.audio_input("🎤 Speak your question / अपना सवाल बोलें")
    if audio is not None:
        data = audio.getvalue()
        if st.session_state.get("audio_hash") != hash(data):  # transcribe each recording only once
            st.session_state.audio_hash = hash(data)
            try:
                with st.spinner("Listening..."):
                    st.session_state.heard_edit = voice.transcribe(data, hint)
            except Exception as e:
                st.error(f"Could not understand the audio: {e}")
    if st.session_state.get("heard_edit"):
        st.text_area("I heard this. Fix anything wrong, then press Ask (numbers matter!):", key="heard_edit")
        st.button("Ask / पूछें", on_click=_submit_heard)

    q = st.session_state.pop("queued", None) or st.chat_input("e.g. What documents do I need? / मुझे कौन से दस्तावेज़ चाहिए?")
    if q:
        lang = voice.detect_lang(q)  # the answer follows the language of the question
        try:
            search_q = voice.to_english(q) if lang == "hi" else q
        except llm.LLMUnavailable:
            st.warning("Hindi translation is temporarily unavailable. Please try again in a minute, or ask in English. / कृपया एक मिनट बाद फिर कोशिश करें।")
            st.stop()
        st.chat_message("user").markdown(q)
        if lang == "hi":
            st.caption(f"Searching documents for: {search_q}")
        answer, _ = chat_reply(retriever, profile, st.session_state.history, q, lang, search_q)
        st.chat_message("assistant").markdown(answer)
        st.caption(f"Answered by {llm.LAST_PROVIDER}")
        if speak_on:
            mp3 = voice.speak(answer, lang)
            if mp3:
                st.audio(mp3, format="audio/mp3")
        if not answer.startswith("⚠️"):  # don't feed the fallback notice back to the model as history
            st.session_state.history += [{"role": "user", "content": q}, {"role": "assistant", "content": answer}]
    if st.sidebar.button("Start over"):
        st.session_state.clear()
        st.rerun()

st.sidebar.caption(f"Documents last checked: {last_checked()}")
if st.sidebar.button("Check for updates now"):
    get_retriever.clear()
    st.session_state.pop("plan", None)
    st.rerun()
