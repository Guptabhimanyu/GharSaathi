def lang() -> str:
    return st.session_state.get("lang", "en")


def t(key: str, **kw) -> str:
    s = T[lang()][key]
    return s.format(**kw) if kw else s


def L(opt):
    if opt == SELECT:
        return t("select")
    if opt == OTHER_CITY:
        return t("other_city")
    return HI.get(opt, opt) if lang() == "hi" else opt


# ------------------------------------------------------------------ data helpers
@st.cache_resource(show_spinner="Loading documents...")
def get_retriever():
    return Retriever()


@st.cache_data
def load_cities() -> dict:
    try:
        return json.loads(Path("static/cities.json").read_text(encoding="utf-8"))
    except Exception:
        return {}


def last_checked() -> str:
    m = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    dates = [v.get("checked_at", "")[:10] for v in m.values() if v.get("checked_at")]
    return max(dates) if dates else "never"


def _submit_heard():
    st.session_state.queued = st.session_state.heard_edit
    st.session_state.heard_edit = ""
    st.session_state.mic_n = st.session_state.get("mic_n", 0) + 1  # fresh recorder for the next question


def go(step: int):
    st.session_state.step = step


def show_sources(chunks):
    with st.expander(t("sources")):
        for i, c in enumerate(chunks, 1):
            link = f" ([source]({c['url']}))" if c.get("url") else ""
            st.markdown(f"**[{i}]** {c.get('label', c['source'])}, p.{c['page']}, {t('checked')} {c.get('checked') or 'n/a'}{link}")


